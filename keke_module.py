def get_kefen(hour, minute):
    """确定时辰八刻"""
    adjusted_hour = hour
    if adjusted_hour == 0:
        adjusted_hour = 24
    
    shichen_start = ((adjusted_hour - 1) // 2) * 2 + 1
    if shichen_start == 25:
        shichen_start = 1
    
    minute_in_shichen = ((adjusted_hour - shichen_start) * 60) + minute
    
    k = (minute_in_shichen // 15) + 1
    if k > 8: k = 8
    if k < 1: k = 1
    
    return k, minute_in_shichen


